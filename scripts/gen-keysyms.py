"""Writes core/voice/src/typer/x11/keysyms.rs from X11's keysymdef.h.

    python3 -I scripts/gen-keysyms.py /usr/include/X11/keysymdef.h > core/voice/src/typer/x11/keysyms.rs

Each legacy keysym whose comment names one Unicode character exactly ("U+0444", not "(U+0444)")
and whose character is past Latin-1 becomes a (code point, keysym) pair, sorted by code point.
"""
import re
import sys

PAT = re.compile(r'^#define XK_\w+\s+0x([0-9a-fA-F]+)\s*/\* U\+([0-9A-Fa-f]{4,6}) ')

pairs = {}
for line in open(sys.argv[1], encoding='utf-8'):
    m = PAT.match(line)
    if not m:
        continue
    sym, cp = int(m.group(1), 16), int(m.group(2), 16)
    # Below 0x100 is Latin-1, which keysym() already maps; 0xfe00 up are function keys.
    if 0x100 <= sym < 0xfe00 and cp > 0xff:
        pairs.setdefault(cp, sym)

assert all(cp <= 0xffff for cp in pairs), 'a code point past u16'
print('//! Legacy X keysyms for characters past Latin-1: (code point, keysym), sorted by code point.')
print('//! Generated by scripts/gen-keysyms.py from keysymdef.h; do not edit by hand.')
print()
print('pub(super) const LEGACY: &[(u16, u16)] = &[')
items = [f'(0x{cp:04x}, 0x{sym:04x})' for cp, sym in sorted(pairs.items())]
for i in range(0, len(items), 4):
    print('    ' + ', '.join(items[i:i + 4]) + ',')
print('];')
